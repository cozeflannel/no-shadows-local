"""Generate apps-script-chat-bot/Generated.gs (and Channels.gs) from the YAML config (the single source of truth).

The Apps Script bot gets what it needs: the alert template labels, the exposure-tag / sensitive-topic / product
taxonomy, network domains, engagement levels, the 14-day novelty settings, the emoji legend, the Gemini check
instructions and the `burson_qa` settings (V1); plus, for the Social Alert drafts (V2), the escalation thresholds from
the Collection Requirements, the distribution lists (config/distribution.yaml) and the email settings. The ~1,000
Google-owned channels (config/channel_owners.json) go to Channels.gs. No rosters.

    .venv/bin/python -m scripts.build_apps_script          # write Generated.gs and Channels.gs
    .venv/bin/python -m scripts.build_apps_script --check  # exit 1 if either is out of date
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path
from typing import Any

from triage_agent.config import AgentConfig, load_config
from triage_agent.qa.rules import NETWORK_ALIASES

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "apps-script-chat-bot" / "Generated.gs"
CHANNELS_TARGET = ROOT / "apps-script-chat-bot" / "Channels.gs"

HEADER = """\
// GENERATED by scripts/build_apps_script.py from config/default_config.yaml + config/distribution.yaml.
// Do not edit by hand. After changing the YAML, run:  .venv/bin/python -m scripts.build_apps_script
// Then push the Apps Script project (clasp push) or paste this file into the editor.
"""

CHANNELS_HEADER = """\
// GENERATED by scripts/build_apps_script.py from config/channel_owners.json (Google-owned social channels and their
// owners: the Channel Owner group of the Social Alert email). Do not edit by hand.
"""


def js_regex(pattern: str | None) -> dict[str, str] | None:
    """Python regex -> {source, flags} for JS: leading inline flags like (?im) become RegExp flags; `u` always
    (so emoji in character classes are single code points)."""
    if not pattern:
        return None
    flags = "u"
    m = re.match(r"^\(\?([a-zA-Z]+)\)", pattern)
    if m:
        flags += "".join(f for f in m.group(1) if f in "imsx" and f != "x")
        pattern = pattern[m.end() :]
    return {"source": pattern, "flags": "".join(sorted(set(flags)))}


def _nonempty(d: dict[str, Any]) -> dict[str, Any]:
    return {k: v for k, v in d.items() if v not in (None, [], {}, "", False)}


def escalation_rules(cfg: AgentConfig) -> dict[str, Any]:
    """The Collection Requirements' escalation thresholds (port target: triage_agent/qa/requirements.py)."""
    col, yt = cfg.collection, cfg.protocols.youtube
    return {
        "language": col.language,
        "high_engagement_threshold": col.high_engagement_threshold,
        "ongoing_urgent_requires_kof": col.ongoing_urgent_requires_kof,
        "remap_suspension_bias": col.remap_suspension_bias,
        "politics_us_locations": list(col.politics_us_locations),
        "redundant_pairs": [[p.exposure_tag, p.risk_tag] for p in col.redundant_pairs],
        "briefed_topics": [
            _nonempty(b.model_dump(mode="json")) | {"active": b.active} for b in col.briefed_topics
        ],
        "exclusions": [
            _nonempty({"id": r.id, "pattern": r.pattern}) | {"unless_risk_keywords": r.unless_risk_keywords}
            for r in col.exclusions
            if r.enabled
        ],
        "patterns": dict(col.patterns),
        "generic_criticism_tags": list(col.generic_criticism_tags),
        "bias_tags": list(col.bias_tags),
        "hallucination_tags": list(col.hallucination_tags),
        "hallucination_products": list(col.hallucination_products),
        "product_mistake_tags": list(col.product_mistake_tags),
        "always_alert_tags": [t.name for t in col.exposure_tags if t.always_alert],
        "youtube": {
            "enabled": yt.enabled,
            "sensitive_topics": list(yt.sensitive_topics_for_low_engagement),
            "sensitive_exposure_tags": list(yt.sensitive_exposure_tags),
        },
    }


def distribution_data(cfg: AgentConfig) -> dict[str, Any]:
    """Who a Social Alert goes to (port target: triage_agent/routing.py plan_recipients)."""
    dist = cfg.distribution
    return {
        "fallback_product": dist.fallback_product,
        "products": [
            _nonempty(
                {
                    "name": p.name,
                    "group_name": p.group_name,
                    "aliases": list(p.aliases),
                    "pa": list(p.pa),
                    "gup": list(p.gup),
                    "conditional": [
                        {
                            "label": c.label,
                            "min_engagement": c.min_engagement,
                            "recipients": list(c.recipients),
                        }
                        for c in p.conditional
                    ],
                    "execs": list(p.execs),
                    "execs_rule": p.execs_rule if p.execs else None,
                    "deprecated": p.deprecated,
                    "redirect_to": list(p.redirect_to),
                }
            )
            for p in dist.products
        ],
        "groups": [
            _nonempty(
                {
                    "name": g.name,
                    "action_code": g.action_code,
                    "auto_include": g.auto_include,
                    "recipients": list(g.recipients),
                    "triggers": _nonempty(g.triggers.model_dump(mode="json")) | {"match": g.triggers.match},
                }
            )
            for g in dist.groups
        ],
        "regional_leads": [
            _nonempty(
                {
                    "region": r.region,
                    "aliases": list(r.aliases),
                    "parent_region": r.parent_region,
                    "recipients": list(r.recipients),
                    "reputational_risk_recipients": list(r.reputational_risk_recipients),
                }
            )
            for r in dist.regional_leads
        ],
    }


def load_precedents() -> list[dict[str, Any]]:
    p = ROOT / "config" / "precedents.json"
    if not p.exists():
        return []
    return json.loads(p.read_text(encoding="utf-8"))


def build_data(cfg: AgentConfig) -> dict[str, Any]:
    tpl, col, dist, esc = (
        cfg.alert_template,
        cfg.collection,
        cfg.distribution,
        cfg.escalation,
    )
    return {
        "config_version": cfg.version,
        "timezone": cfg.timezone,
        "prefix": cfg.agent.message_prefix,
        "models": {
            "triage": cfg.models.triage,
            "location": cfg.models.location,
            "temperature": cfg.models.temperature_triage,
        },
        "settings": cfg.burson_qa.model_dump(mode="json"),
        "auto_apply_min_confidence": cfg.corrections.auto_apply_min_confidence,
        "never_auto_correct": list(cfg.corrections.never_auto_correct),
        "detection": {
            "sender_names": list(tpl.detection.sender_names),
            "text_regex": js_regex(tpl.detection.text_regex),
            "min_labels": tpl.detection.min_labels_matched,
        },
        "flag_patterns": {k: js_regex(v) for k, v in tpl.flag_patterns.items()},
        "fields": [
            {
                k: v
                for k, v in {
                    "name": f.name,
                    "labels": list(f.labels),
                    "type": f.type,
                    "allowed": list(f.allowed or []),
                    "required": f.required,
                    "correctable": f.correctable,
                    "min": f.min,
                    "not_in_future": f.not_in_future,
                    "max_age_days": f.max_age_days,
                    "numeric_fallback": f.numeric_fallback,
                }.items()
                if v not in (None, [], False) or k in ("name", "type")
            }
            for f in tpl.fields
        ],
        "exposure_tags": [
            {
                "name": t.name,
                "priority": t.priority,
                "category": t.category,
                "aliases": list(t.aliases),
                "description": t.description,
            }
            for t in col.exposure_tags
        ],
        "sensitive_topics": [
            {"name": t.name, "aliases": list(t.aliases), "description": t.description}
            for t in col.sensitive_topics
        ],
        "products": [
            {
                k: v
                for k, v in {
                    "name": p.name,
                    "aliases": list(p.aliases),
                    "deprecated": p.deprecated,
                    "redirect_to": list(p.redirect_to),
                }.items()
                if v not in ([], False) or k == "name"
            }
            for p in dist.products
        ],
        "platform_domains": cfg.reference_lists.get("platform_domains") or {},
        "network_aliases": dict(NETWORK_ALIASES),
        "engagement_levels": [
            {"name": lv.name, "emoji": lv.emoji, "min": lv.min} for lv in col.engagement_levels
        ],
        "viral_kof_label": col.viral_kof_label,
        "novelty_days": col.novelty_days,
        "novelty_min_jaccard": col.novelty_min_jaccard,
        "issue_stopwords": list(col.issue_stopwords),
        "legend": [
            _nonempty(
                {
                    "emoji": a.emoji,
                    "code": a.code,
                    "label": a.label,
                    "kind": a.kind,
                    "group": getattr(a, "group", None),
                }
            )
            for a in cfg.actions
        ],
        "llm_checks": [
            {
                "id": c.id,
                "correctable_field": c.correctable_field,
                "severity": c.severity.value,
                "fields": list(c.fields),
                "instruction": c.instruction,
            }
            for c in tpl.llm_checks
            if c.enabled
        ],
        "judgment_rules": list(col.do_not_escalate),
        "precedents": load_precedents(),
        # V2: Social Alert drafts
        "escalation_rules": escalation_rules(cfg),
        "distribution": distribution_data(cfg),
        "email": {
            "from_name": esc.from_name,
            "from_email": esc.from_email,
            "reply_subject_prefix": esc.reply_subject_prefix,
            "default_to": list(esc.default_to),
            "default_cc": list(esc.default_cc),
            "recipients_in": esc.recipients_in,
            "stand_in": esc.stand_in.strip(),
            "tns_urgent": cfg.tns.urgent_alias.strip(),
        },
        # 🧑‍💻: [Internal] SLRR P0 + Sensitive Topics + Product Failure Escalation Protocol
        "leadership": cfg.protocols.leadership.model_dump(mode="json"),
        # Names for addresses the bot mentions (e.g. the leads a stand-in DM would have gone to)
        "people": {a.email.lower(): a.name for a in cfg.analysts if a.email},
    }


def channels_data(cfg: AgentConfig) -> list[dict[str, Any]]:
    keep = (
        "account_url",
        "handle",
        "owners",
        "region",
        "account_name",
        "platform",
        "team_brand",
    )
    return [_nonempty({k: getattr(c, k) for k in keep}) for c in cfg.distribution.channel_owners if c.owners]


def render(cfg: AgentConfig) -> str:
    body = json.dumps(build_data(cfg), ensure_ascii=False, indent=1)
    return f"{HEADER}\n// config version: {cfg.version}\nconst GEN = {body};\n"


def render_channels(cfg: AgentConfig) -> str:
    rows = ",\n".join(json.dumps(c, ensure_ascii=False, separators=(",", ":")) for c in channels_data(cfg))
    return f"{CHANNELS_HEADER}\nconst GEN_CHANNEL_OWNERS = [\n{rows}\n];\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if Generated.gs or Channels.gs is out of date",
    )
    args = parser.parse_args(argv)
    prev_flag = os.environ.get("SLRR_FETCH_SHEET_GROUPS")
    os.environ["SLRR_FETCH_SHEET_GROUPS"] = "0"
    try:
        cfg = load_config()
    finally:
        if prev_flag is None:
            os.environ.pop("SLRR_FETCH_SHEET_GROUPS", None)
        else:
            os.environ["SLRR_FETCH_SHEET_GROUPS"] = prev_flag
    outputs = {TARGET: render(cfg), CHANNELS_TARGET: render_channels(cfg)}
    if args.check:
        stale = [
            p for p, text in outputs.items() if (p.read_text(encoding="utf-8") if p.exists() else "") != text
        ]
        for p in stale:
            print(
                f"{p.relative_to(ROOT)} is out of date: run python -m scripts.build_apps_script",
                file=sys.stderr,
            )
        if stale:
            return 1
        print(", ".join(str(p.relative_to(ROOT)) for p in outputs) + " up to date")
        return 0
    for p, text in outputs.items():
        p.write_text(text, encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT)} ({len(text):,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
